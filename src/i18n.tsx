function detectLang(): Lang {
  const saved = store.get('lang');
  if (saved === 'tr' || saved === 'en' || saved === 'de') return saved;
  const nav = (navigator.language || '').slice(0, 2);
  return nav === 'de' || nav === 'en' ? nav : 'tr';
}

function makeI18n(lang: Lang, setLang: (l: Lang) => void) {
  const locale = LOCALES[lang];
  const term = (value: string) => (lang === 'tr' ? value : TERMS[value]?.[lang] ?? value);
  const number = (n: number) => String(Math.round(n * 100) / 100).replace('.', lang === 'en' ? '.' : ',');
  const amount = (value: number, unit: string | null) => {
    const base = toBaseUnit(value, unit);
    return formatAmount(base.amount, base.unit, { unitLabel: term, decimal: lang === 'en' ? '.' : ',' });
  };
  // Tarif/malzeme gibi kayıtlardaki çevrilebilir alan: çevirisi yoksa Türkçesine düşer.
  const pick = <T extends object>(row: T, field: keyof T & string): string => {
    const translated = lang === 'tr' ? null : (row as Record<string, unknown>)[`${field}_${lang}`];
    return String(translated || row[field] || '');
  };
  return {
    lang,
    setLang,
    pick,
    locale,
    term,
    number,
    amount,
    t: (key: Key, params: Record<string, string | number> = {}) =>
      STRINGS[lang][key].replace(/\{(\w+)\}/g, (_, p) => String(params[p] ?? '')),
    servings: (n: number) => STRINGS[lang].servings.replace('{n}', number(n)),
    dayName: (date: Date) => new Intl.DateTimeFormat(locale, { weekday: 'long' }).format(date),
    dayMonth: (date: Date, month: 'long' | 'short' = 'long') => new Intl.DateTimeFormat(locale, { day: 'numeric', month }).format(date),
    slot: (id: string) => STRINGS[lang][id === 'kahvalti' ? 'breakfast' : id === 'ogle' ? 'lunch' : 'dinner'],
  };
}

type I18n = ReturnType<typeof makeI18n>;
const Ctx = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(detectLang);
  const value = useMemo(
    () =>
      makeI18n(lang, (l) => {
        store.set('lang', l);
        setLangState(l);
      }),
    [lang]
  );
  // <html lang> ilk açılışta da doğru olsun: CSS büyük harf dönüşümü dile bakar (tr'de i → İ, "DİNNER" hatası).
  useEffect(() => {
    document.documentElement.lang = lang;
    document.title = STRINGS[lang].appTitle;
  }, [lang]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error('I18nProvider eksik');
  return ctx;
}
